create or replace function public.prepare_product_insert()
returns trigger language plpgsql set search_path = '' as $$
declare n bigint;
begin
  if not public.is_owner() then raise exception 'Acesso negado.'; end if;
  n := nextval('public.bp_product_number_seq');
  new.product_code := 'BP-' || lpad(n::text, 6, '0');
  new.slug := 'peca-' || lower(new.product_code);
  new.publication_status := 'draft'; -- só publicar depois que existir ao menos uma foto
  new.created_by := auth.uid();
  new.updated_by := auth.uid();
  new.version := 1;
  new.created_at := now();
  new.updated_at := now();
  new.published_at := null;
  return new;
end;
$$;
drop trigger if exists trg_prepare_product_insert on public.products;
create trigger trg_prepare_product_insert before insert on public.products for each row execute function public.prepare_product_insert();

create or replace function public.audit_product()
returns trigger language plpgsql security definer set search_path = '' as $$
declare a text;
declare summary jsonb;
begin
  if tg_op = 'INSERT' then
    a := 'created'; summary := jsonb_build_object('name',new.name,'price_cents',new.price_cents);
  elsif tg_op = 'DELETE' then
    a := 'deleted'; summary := jsonb_build_object('name',old.name);
  else
    a := 'updated'; summary := jsonb_build_object(
      'old_price_cents',old.price_cents,'new_price_cents',new.price_cents,
      'old_publication_status',old.publication_status,'new_publication_status',new.publication_status,
      'old_availability_status',old.availability_status,'new_availability_status',new.availability_status,
      'version',new.version
    );
  end if;
  insert into public.product_audit_logs(product_id,product_code,owner_id,action,change_summary)
  values (case when tg_op='DELETE' then old.id else new.id end,
          case when tg_op='DELETE' then old.product_code else new.product_code end,
          auth.uid(),a,summary);
  return case when tg_op='DELETE' then old else new end;
end;
$$;
drop trigger if exists trg_audit_product on public.products;
create trigger trg_audit_product after insert or update or delete on public.products for each row execute function public.audit_product();

-- Evita sobrescrever a edição de outro proprietário.
-- Atualizações de produtos são concedidas apenas por esta função, nunca UPDATE direto do cliente.
create or replace function public.owner_update_product(p_id uuid,p_expected_version integer,p_patch jsonb)
returns public.products language plpgsql security definer set search_path = '' as $$
declare current_product public.products;
declare changed public.products;
declare bad_key text;
begin
  if not public.is_owner() then raise exception 'Acesso negado.'; end if;
  if p_patch is null or jsonb_typeof(p_patch) <> 'object' then raise exception 'Dados inválidos.'; end if;
  select k into bad_key from jsonb_object_keys(p_patch) as k
  where k not in ('name','description','category_id','brand','size','color','condition','price_cents','quantity','availability_status','publication_status','featured','measures','archived_at') limit 1;
  if bad_key is not null then raise exception 'Campo não permitido: %',bad_key; end if;
  select * into current_product from public.products where id=p_id for update;
  if not found then raise exception 'Produto não encontrado.'; end if;
  if current_product.version <> p_expected_version then
    raise exception 'CONFLITO_DE_VERSAO: Este produto foi alterado por outro proprietário. Atualize a página antes de salvar.' using errcode='P0001';
  end if;
  if (p_patch->>'publication_status') = 'published'
    and not exists(select 1 from public.product_images where product_id=p_id) then
    raise exception 'Adicione uma fotografia antes de publicar.';
  end if;
  update public.products p set
    name = case when p_patch ? 'name' then p_patch->>'name' else p.name end,
    description = case when p_patch ? 'description' then p_patch->>'description' else p.description end,
    category_id = case when p_patch ? 'category_id' then nullif(p_patch->>'category_id','')::uuid else p.category_id end,
    brand = case when p_patch ? 'brand' then p_patch->>'brand' else p.brand end,
    size = case when p_patch ? 'size' then p_patch->>'size' else p.size end,
    color = case when p_patch ? 'color' then p_patch->>'color' else p.color end,
    condition = case when p_patch ? 'condition' then p_patch->>'condition' else p.condition end,
    price_cents = case when p_patch ? 'price_cents' then (p_patch->>'price_cents')::integer else p.price_cents end,
    quantity = case when p_patch ? 'quantity' then (p_patch->>'quantity')::integer else p.quantity end,
    availability_status = case when p_patch ? 'availability_status' then p_patch->>'availability_status' else p.availability_status end,
    publication_status = case when p_patch ? 'publication_status' then p_patch->>'publication_status' else p.publication_status end,
    featured = case when p_patch ? 'featured' then (p_patch->>'featured')::boolean else p.featured end,
    measures = case when p_patch ? 'measures' then p_patch->'measures' else p.measures end,
    archived_at = case when p_patch ? 'archived_at' then (p_patch->>'archived_at')::timestamptz else p.archived_at end,
    published_at = case when p_patch->>'publication_status' = 'published' and p.published_at is null then now() else p.published_at end,
    version = p.version + 1,
    updated_by = auth.uid(),updated_at=now()
    where p.id=p_id returning * into changed;
  return changed;
end;
$$;
revoke all on function public.owner_update_product(uuid,integer,jsonb) from public;
grant execute on function public.owner_update_product(uuid,integer,jsonb) to authenticated;

-- Alterações em fotos também mudam a versão do produto e entram na auditoria.
create or replace function public.bump_product_on_image_change()
returns trigger language plpgsql security definer set search_path = '' as $$
declare pid uuid;
begin
  pid := case when tg_op='DELETE' then old.product_id else new.product_id end;
  update public.products set version=version+1,updated_at=now(),updated_by=auth.uid() where id=pid;
  return case when tg_op='DELETE' then old else new end;
end;
$$;
drop trigger if exists trg_image_change on public.product_images;
create trigger trg_image_change after insert or update or delete on public.product_images for each row execute function public.bump_product_on_image_change();

create or replace function public.check_last_photo()
returns trigger language plpgsql set search_path = '' as $$
begin
  if (select publication_status from public.products where id=old.product_id)='published'
    and (select count(*) from public.product_images where product_id=old.product_id)<=1 then
    raise exception 'Oculte a peça ou envie outra foto antes de remover a última fotografia.';
  end if;
  return old;
end;
$$;
drop trigger if exists trg_check_last_photo on public.product_images;
create trigger trg_check_last_photo before delete on public.product_images for each row execute function public.check_last_photo();

