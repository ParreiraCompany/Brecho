create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  product_code text unique not null,
  slug text unique not null,
  name text not null check(char_length(trim(name)) between 2 and 140),
  description text not null default '' check(char_length(description) <= 4000),
  category_id uuid references public.categories(id) on delete set null,
  brand text not null default '' check(char_length(brand) <= 100),
  size text not null default '' check(char_length(size) <= 50),
  color text not null default '' check(char_length(color) <= 90),
  condition text not null default 'Bom estado' check (condition in ('Novo com etiqueta','Novo sem etiqueta','Excelente estado','Bom estado','Estado regular')),
  price_cents integer not null check(price_cents >= 0 and price_cents <= 999999999),
  quantity integer not null default 1 check(quantity >= 0 and quantity <= 100000),
  availability_status text not null default 'available' check(availability_status in ('available','reserved','sold')),
  publication_status text not null default 'draft' check(publication_status in ('draft','published','hidden')),
  featured boolean not null default false,
  measures jsonb not null default '{}'::jsonb,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz,
  archived_at timestamptz,
